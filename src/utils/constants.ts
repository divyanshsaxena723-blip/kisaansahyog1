export function evaluatePriceGuardrail(cropRate: number, benchmarkRate: number) {
  const diffPercent = ((cropRate - benchmarkRate) / benchmarkRate) * 100;
  if (diffPercent < -15) {
    return { status: 'distress', color: 'text-red-600 bg-red-50 border-red-200', message: 'चेतावनी: संकटकालीन बिक्री (Distress Sale) — न्यूनतम समर्थन मूल्य से काफी नीचे।' };
  } else if (diffPercent > 40) {
    return { status: 'high', color: 'text-amber-600 bg-amber-50 border-amber-200', message: 'सावधान: दर बाज़ार औसत से काफी अधिक है, खरीदार मिलने में देरी हो सकती है।' };
  }
  return { status: 'fair', color: 'text-emerald-700 bg-emerald-50 border-emerald-200', message: 'उचित बाज़ार दर: इस मूल्य पर शीघ्र सौदे की संभावना है।' };
}

